#!/usr/bin/env python3
"""Set up the local knowledge-base stack after `podman-compose up` (local-kb/PLAN.md, Phase 1).

    python local_init.py env    write local-kb/.env with random credentials, or add missing ones
    python local_init.py init   bucket, bucket event, the least-privilege OpenSearch user, and pg
    python local_init.py pg     AWS's Aurora setup SQL against the local Postgres, only
    python local_init.py pg --table bedrock_integration.other_kb   another RDS KB's table

`init` and `pg` are idempotent: run them as often as you like. They are the local version of the
cloud module's policies — the bucket stands in for the S3 data source, the bucket event for the
S3 → Lambda → StartIngestionJob wiring, the `bedrock-kb` user for the AOSS data-access policy,
and `bedrock_user` for the role AWS's Aurora guide creates.
"""

from __future__ import annotations

import argparse
import base64
import json
import secrets
import ssl
import string
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

import boto3
from botocore.exceptions import ClientError

REPO = Path(__file__).resolve().parents[2]
ENV_FILE = REPO / "local-kb" / ".env"

S3_ENDPOINT = "http://127.0.0.1:9000"
DASHBOARDS = "http://127.0.0.1:5601"
SAVED_OBJECTS = REPO / "local-kb" / "dashboards" / "bedrock-kb.ndjson"
OPENSEARCH = "https://127.0.0.1:9200"
BUCKET = "kb-data"
PREFIX = "kb/"
WEBHOOK_TARGET = "kb"  # RUSTFS_NOTIFY_WEBHOOK_*_KB in compose.yaml

ROLE = "bedrock_kb"
USER = "bedrock-kb"
INDEX_PATTERN = "bedrock-knowledge-base-*"

PG_HOST = "127.0.0.1"
PG_PORT = 5432
PG_USER = "bedrock_user"  # AWS's name for the role Bedrock connects as


# ------------------------------------------------------------------------ env


def load_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        raise SystemExit(f"{ENV_FILE} is missing. Run `make local-up` (or `local_init.py env`).")
    pairs = (
        line.split("=", 1)
        for line in ENV_FILE.read_text().splitlines()
        if "=" in line and not line.lstrip().startswith("#")
    )
    return {key.strip(): value.strip() for key, value in pairs}


def strong_password() -> str:
    """OpenSearch's strength check wants upper, lower, digit and special. `$` is avoided because
    compose files interpolate it."""
    alphabet = string.ascii_letters + string.digits
    core = "".join(secrets.choice(alphabet) for _ in range(20))
    return f"Kb{core}9!"


def write_env() -> None:
    """Create .env, or add the keys a newer compose.yaml needs; existing values are kept, since
    the services only read their passwords on first start."""
    generated = {
        "RUSTFS_ACCESS_KEY": f"kb-{secrets.token_hex(6)}",
        "RUSTFS_SECRET_KEY": secrets.token_urlsafe(24),
        "OPENSEARCH_INITIAL_ADMIN_PASSWORD": strong_password(),
        "BEDROCK_KB_PASSWORD": strong_password(),
        "POSTGRES_PASSWORD": secrets.token_urlsafe(24),
        "BEDROCK_PG_PASSWORD": secrets.token_urlsafe(24),
    }
    if not ENV_FILE.exists():
        ENV_FILE.write_text("# Generated by python/scripts/local_init.py env. Gitignored.\n")
        ENV_FILE.chmod(0o600)
    missing = [key for key in generated if key not in load_env()]
    if not missing:
        print(f"{ENV_FILE.relative_to(REPO)} is complete — leaving it alone")
        return
    with ENV_FILE.open("a") as env:
        env.writelines(f"{key}={generated[key]}\n" for key in missing)
    print(f"{ENV_FILE.relative_to(REPO)}: added {', '.join(missing)}")


# ------------------------------------------------------------------- clients


def s3_client(env: dict[str, str]) -> Any:
    return boto3.client(
        "s3",
        endpoint_url=S3_ENDPOINT,
        region_name="us-east-1",
        aws_access_key_id=env["RUSTFS_ACCESS_KEY"],
        aws_secret_access_key=env["RUSTFS_SECRET_KEY"],
    )


def opensearch(
    method: str, path: str, user: str, password: str, body: Any = None
) -> tuple[int, Any]:
    """One request to the local cluster. The demo certificate is self-signed, so verification
    is off — acceptable only because the port is bound to 127.0.0.1."""
    data = json.dumps(body).encode() if body is not None else None
    token = base64.b64encode(f"{user}:{password}".encode()).decode()
    request = urllib.request.Request(  # noqa: S310 - fixed local URL
        OPENSEARCH + path,
        data=data,
        method=method,
        headers={"Authorization": f"Basic {token}", "Content-Type": "application/json"},
    )
    context = ssl.create_default_context()
    context.check_hostname = False
    context.verify_mode = ssl.CERT_NONE
    try:
        with urllib.request.urlopen(request, context=context, timeout=30) as response:  # noqa: S310
            return int(response.status), json.loads(response.read() or b"null")
    except urllib.error.HTTPError as exc:
        return int(exc.code), exc.read().decode(errors="replace")


def wait_for(name: str, check: Any, timeout: int = 180) -> None:
    deadline = time.monotonic() + timeout
    while True:
        try:
            if check():
                print(f"{name} is up")
                return
        except (OSError, ClientError):
            pass
        if time.monotonic() > deadline:
            raise SystemExit(f"{name} did not come up within {timeout}s — check podman logs")
        time.sleep(3)


# --------------------------------------------------------------------- steps


def ensure_bucket(s3: Any) -> None:
    # CreateBucket on a bucket you already own succeeds silently (as on AWS in us-east-1), so
    # ask first rather than infer from the response.
    try:
        s3.head_bucket(Bucket=BUCKET)
        print(f"bucket {BUCKET} exists")
    except ClientError:
        s3.create_bucket(Bucket=BUCKET)
        print(f"created bucket {BUCKET}")


def ensure_bucket_event(s3: Any) -> str:
    """Point created/removed events under the prefix at the webhook target, through the standard
    S3 API. RustFS's docs show the target ARN both with an empty region and with us-east-1, so
    try each and return the one the server accepts."""
    last_error: ClientError | None = None
    for arn in (
        f"arn:rustfs:sqs::{WEBHOOK_TARGET}:webhook",
        f"arn:rustfs:sqs:us-east-1:{WEBHOOK_TARGET}:webhook",
    ):
        config = {
            "QueueConfigurations": [
                {
                    "Id": "kb-sync",
                    "QueueArn": arn,
                    "Events": ["s3:ObjectCreated:*", "s3:ObjectRemoved:*"],
                    "Filter": {"Key": {"FilterRules": [{"Name": "prefix", "Value": PREFIX}]}},
                }
            ]
        }
        try:
            s3.put_bucket_notification_configuration(
                Bucket=BUCKET, NotificationConfiguration=config
            )
        except ClientError as exc:
            last_error = exc
            continue
        print(f"bucket event: s3:ObjectCreated:* + s3:ObjectRemoved:* under {PREFIX} -> {arn}")
        return arn
    assert last_error is not None
    raise SystemExit(f"no webhook ARN form was accepted: {last_error}")


def ensure_opensearch_user(admin_password: str, kb_password: str) -> None:
    """Least privilege for the worker and runtime: read/write the KB indexes and manage their
    search pipelines, nothing else. The local version of the AOSS data-access policy."""
    role = {
        "cluster_permissions": [
            "cluster_composite_ops",  # _bulk, _mget, _msearch
            "cluster:admin/search/pipeline/*",  # the hybrid-search normalization pipeline
        ],
        "index_permissions": [
            {
                "index_patterns": [INDEX_PATTERN],
                "allowed_actions": [
                    "crud",
                    "search",
                    "create_index",
                    "indices:admin/get",  # HEAD <index>: does the vector index exist yet?
                    "indices:admin/mapping/put",
                ],
            }
        ],
    }
    steps = [
        (f"/_plugins/_security/api/roles/{ROLE}", role),
        (
            f"/_plugins/_security/api/internalusers/{USER}",
            {"password": kb_password, "description": "local Bedrock KB worker and runtime"},
        ),
        (f"/_plugins/_security/api/rolesmapping/{ROLE}", {"users": [USER]}),
    ]
    for path, body in steps:
        status, detail = opensearch("PUT", path, "admin", admin_password, body)
        if status not in (200, 201):
            raise SystemExit(f"PUT {path}: HTTP {status} {detail}")
    # authinfo answers any authenticated user; GET / would need cluster:monitor/main, which
    # this role deliberately lacks.
    status, detail = opensearch("GET", "/_plugins/_security/authinfo", USER, kb_password)
    if status != 200 or ROLE not in detail.get("roles", []):
        raise SystemExit(f"{USER} login check failed: HTTP {status} {detail}")
    print(f"OpenSearch user {USER} -> role {ROLE} on {INDEX_PATTERN}")


def clear_create_index_block(admin_password: str) -> None:
    """OpenSearch persists ``cluster.blocks.create_index`` when a node crosses its high disk
    watermark, and keeps it after the disk recovers or the watermarks change. compose.yaml sets
    the watermarks as free space; this lifts a block left over from before."""
    _, settings = opensearch(
        "GET", "/_cluster/settings?flat_settings=true", "admin", admin_password
    )
    if settings.get("persistent", {}).get("cluster.blocks.create_index") == "true":
        opensearch(
            "PUT",
            "/_cluster/settings",
            "admin",
            admin_password,
            {"persistent": {"cluster.blocks.create_index": None}},
        )
        print("cleared a leftover create-index block (the disk crossed a watermark earlier)")


def import_dashboards(admin_password: str) -> None:
    """Load the index pattern, the "Bedrock KB — internals" saved search and the chunks-per-file
    table into both tenants: multi-tenancy is on, and a first login lands in Private."""
    boundary = secrets.token_hex(16)
    payload = (
        (
            f"--{boundary}\r\n"
            f'Content-Disposition: form-data; name="file"; filename="{SAVED_OBJECTS.name}"\r\n'
            "Content-Type: application/ndjson\r\n\r\n"
        ).encode()
        + SAVED_OBJECTS.read_bytes()
        + f"\r\n--{boundary}--\r\n".encode()
    )
    token = base64.b64encode(f"admin:{admin_password}".encode()).decode()
    for tenant in ("global", "private"):
        request = urllib.request.Request(  # noqa: S310 - fixed local URL
            f"{DASHBOARDS}/api/saved_objects/_import?overwrite=true",
            data=payload,
            method="POST",
            headers={
                "Authorization": f"Basic {token}",
                "Content-Type": f"multipart/form-data; boundary={boundary}",
                "osd-xsrf": "true",
                "securitytenant": tenant,
            },
        )
        with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310
            result = json.loads(response.read())
        if not result.get("success"):
            raise SystemExit(f"Dashboards import into {tenant} failed: {result}")
    print(f"Dashboards: imported {result['successCount']} saved objects into Global and Private")


def dashboards_up(admin_password: str) -> bool:
    token = base64.b64encode(f"admin:{admin_password}".encode()).decode()
    request = urllib.request.Request(  # noqa: S310 - fixed local URL
        f"{DASHBOARDS}/api/status", headers={"Authorization": f"Basic {token}"}
    )
    with urllib.request.urlopen(request, timeout=10) as response:  # noqa: S310
        state = json.loads(response.read())["status"]["overall"]["state"]
    return bool(state == "green")


def ensure_postgres(env: dict[str, str], table: str | None = None, dimensions: int = 1024) -> None:
    """AWS's Aurora setup, verbatim from rds_kb.py: the extension, schema and `bedrock_user` as
    the superuser (Aurora's master user), then the table and its three indexes as
    `bedrock_user`, so it owns them as on AWS. Bedrock validates this layout; it never creates
    it. Each RDS knowledge base needs a table of its own, as on AWS: pass ``table`` for more."""
    import psycopg
    from rds_kb import DATABASE, ITERATIVE_SCAN, SETUP, TABLE

    from aws_ai.local_kb.store_rds import table_sql

    table = table or TABLE

    def connect(user: str, password: str) -> Any:
        return psycopg.connect(
            host=PG_HOST,
            port=PG_PORT,
            dbname=DATABASE,
            user=user,
            password=password,
            autocommit=True,
        )

    def up() -> bool:
        try:
            connect("postgres", env["POSTGRES_PASSWORD"]).close()
        except psycopg.OperationalError:  # still starting: refused, or closed mid-handshake
            return False
        return True

    wait_for("postgres", up)
    with connect("postgres", env["POSTGRES_PASSWORD"]) as admin:
        for sql in SETUP:
            admin.execute(sql.format(password=env["BEDROCK_PG_PASSWORD"]))
        for sql in ITERATIVE_SCAN:
            admin.execute(sql)
    with connect(PG_USER, env["BEDROCK_PG_PASSWORD"]) as user:
        for sql in table_sql(table, dimensions):
            user.execute(sql)
        version = user.execute(
            "SELECT extversion FROM pg_extension WHERE extname = 'vector'"
        ).fetchone()[0]
    print(f"Postgres: pgvector {version}, {table} owned by {PG_USER}")


def init() -> None:
    env = load_env()
    s3 = s3_client(env)
    admin = env["OPENSEARCH_INITIAL_ADMIN_PASSWORD"]

    wait_for("rustfs", lambda: s3.list_buckets() is not None)
    wait_for("opensearch", lambda: opensearch("GET", "/", "admin", admin)[0] == 200)

    ensure_bucket(s3)
    ensure_bucket_event(s3)
    ensure_opensearch_user(admin, env["BEDROCK_KB_PASSWORD"])
    clear_create_index_block(admin)
    wait_for("dashboards", lambda: dashboards_up(admin))
    import_dashboards(admin)
    ensure_postgres(env)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["env", "init", "pg"])
    parser.add_argument(
        "--table", help="pg only: another bedrock_integration.<name> table, for another RDS KB"
    )
    parser.add_argument("--dimensions", type=int, default=1024, help="pg --table only")
    args = parser.parse_args()
    if args.command == "pg":
        ensure_postgres(load_env(), args.table, args.dimensions)
    else:
        {"env": write_env, "init": init}[args.command]()
    return 0


if __name__ == "__main__":
    sys.exit(main())
